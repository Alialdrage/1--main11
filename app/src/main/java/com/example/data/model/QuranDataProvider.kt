    fun cleanArabicText(input: String): String {
        return input
            .replace(Regex("[\\u064B-\\u065F\\u0670\\u06D6-\\u06ED]"), "") // Remove tashkeel/diacritics
            .replace("أ", "ا")
            .replace("إ", "ا")
            .replace("آ", "ا")
            .replace("ى", "ي")
            .replace("ة", "ه")
            .replace(Regex("[^\\u0621-\\u064A\\s]"), "") // Keep only Arabic letters and spaces
            .trim()
            .replace(Regex("\\s+"), " ")
    }
